  const DhakaRadioStation({
    required this.id,
    this.name = '',
    required this.nameBn,
    required this.nameEn,
    this.country = 'Bangladesh',
    this.language = 'Bengali',
    this.category = 'বিনোদন ও গান',
    required this.tagline,
    required this.frequency,
