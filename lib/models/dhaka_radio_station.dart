    required this.streamUrl,
    this.streamType = 'mp3',
    this.verificationStatus = 'verified_live',
    this.enabled = true,
    this.primaryColorValue = 0xFF1E88E5,
    this.lastTested,
    this.lastTestStatus,
  });

  bool get hasDirectStream => streamUrl.trim().isNotEmpty;
  bool get isVerified => verificationStatus == 'verified_live';
  bool get isWebOnly => streamType == 'web_only' || streamUrl.trim().isEmpty;

  Map<String, dynamic> toJson() => {
    'id': id,
    'name': name.isNotEmpty ? name : nameBn,
    'nameBn': nameBn,
    'nameEn': nameEn,
    'country': country,
    'language': language,
    'category': category,
    'tagline': tagline,
    'frequency': frequency,
    'websiteUrl': websiteUrl,
    'streamUrl': streamUrl,
    'streamType': streamType,
    'verificationStatus': verificationStatus,
    'enabled': enabled,
    'primaryColorValue': primaryColorValue,
    'lastTested': lastTested,
    'lastTestStatus': lastTestStatus,
  };

  factory DhakaRadioStation.fromJson(Map<String, dynamic> json) {
    final bn = json['nameBn'] as String? ?? json['name'] as String? ?? '';
    final en = json['nameEn'] as String? ?? json['name'] as String? ?? '';
    return DhakaRadioStation(
      id: json['id'] as String? ?? '',
      name: json['name'] as String? ?? bn,
      nameBn: bn,
      nameEn: en,
      country: json['country'] as String? ?? 'Bangladesh',
      language: json['language'] as String? ?? 'Bengali',
      category: json['category'] as String? ?? 'বিনোদন ও গান',
      tagline: json['tagline'] as String? ?? '',
      frequency: json['frequency'] as String? ?? '',
      websiteUrl: json['websiteUrl'] as String? ?? '',
      streamUrl: json['streamUrl'] as String? ?? '',
      streamType: json['streamType'] as String? ?? 'mp3',
      verificationStatus: json['verificationStatus'] as String? ?? 'verified_live',
      enabled: json['enabled'] as bool? ?? true,
      primaryColorValue: json['primaryColorValue'] as int? ?? 0xFF1E88E5,
      lastTested: json['lastTested'] as String?,
      lastTestStatus: json['lastTestStatus'] as String?,
    );
  }

  DhakaRadioStation copyWith({
    String? id,
    String? name,
    String? nameBn,
    String? nameEn,
    String? country,
    String? language,
    String? category,
    String? tagline,
    String? frequency,
    String? websiteUrl,
    String? streamUrl,
    String? streamType,
    String? verificationStatus,
    bool? enabled,
    int? primaryColorValue,
    String? lastTested,
    String? lastTestStatus,
  }) {
    return DhakaRadioStation(
      id: id ?? this.id,
      name: name ?? this.name,
      nameBn: nameBn ?? this.nameBn,
      nameEn: nameEn ?? this.nameEn,
      country: country ?? this.country,
      language: language ?? this.language,
      category: category ?? this.category,
      tagline: tagline ?? this.tagline,
      frequency: frequency ?? this.frequency,
      websiteUrl: websiteUrl ?? this.websiteUrl,
      streamUrl: streamUrl ?? this.streamUrl,
      streamType: streamType ?? this.streamType,
      verificationStatus: verificationStatus ?? this.verificationStatus,
      enabled: enabled ?? this.enabled,
      primaryColorValue: primaryColorValue ?? this.primaryColorValue,
      lastTested: lastTested ?? this.lastTested,
      lastTestStatus: lastTestStatus ?? this.lastTestStatus,
    );
  }

